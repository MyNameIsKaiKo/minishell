#include "../lexer.h"

void	indexing_lex(t_lexer **lex)
{
	int		i;
	t_lexer	*tmp;

	tmp = *lex;
	i = 1;
	while (tmp->next)
	{
		tmp->index = i;
		i++;
		tmp = tmp->next;
	}
}
